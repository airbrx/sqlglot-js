/** Mirror of CPython's `re.Match`. */
export class PyMatch {
  /**
   * @param {RegExpExecArray} m
   * @param {PyPattern} pattern
   * @param {string} string
   */
  constructor(m, pattern, string) {
    this._m = m;
    this.re = pattern;
    this.string = string;
    this.lastindex = null;
    for (let i = m.length - 1; i >= 1; i -= 1) {
      if (m[i] !== undefined) {
        this.lastindex = i;
        break;
      }
    }
  }
  /** @param {...(number|string)} keys */
  group(...keys) {
    if (keys.length === 0) return this._m[0];
    const vals = keys.map((k) => {
      const i = this.re._groupNumber(k);
      const v = this._m[i];
      return v === undefined ? null : v;
    });
    return keys.length === 1 ? vals[0] : vals;
  }
  groups(dflt = null) {
    const out = [];
    for (let i = 1; i < this._m.length; i += 1) {
      out.push(this._m[i] === undefined ? dflt : this._m[i]);
    }
    return out;
  }
  groupdict(dflt = null) {
    /** @type {Record<string, string|null>} */
    const out = {};
    for (const [name, gid] of Object.entries(this.re.groupindex)) {
      out[name] = this._m[gid] === undefined ? dflt : this._m[gid];
    }
    return out;
  }
  /** @param {number|string} [g] */
  start(g = 0) {
    const i = this.re._groupNumber(g);
    if (i === 0) return this._m.index;
    if (this._m[i] === undefined) return -1;
    // Node exposes per-group indices only with the `d` flag; PyPattern sets it.
    const ind = /** @type {any} */ (this._m).indices;
    return ind && ind[i] ? ind[i][0] : -1;
  }
  /** @param {number|string} [g] */
  end(g = 0) {
    const i = this.re._groupNumber(g);
    if (i === 0) return this._m.index + this._m[0].length;
    if (this._m[i] === undefined) return -1;
    const ind = /** @type {any} */ (this._m).indices;
    return ind && ind[i] ? ind[i][1] : -1;
  }
  /** @param {number|string} [g] */
  span(g = 0) {
    return [this.start(g), this.end(g)];
  }
}

/** Mirror of CPython's compiled `re.Pattern`. */
export class PyPattern {
  /** @param {string} pattern @param {number} flags */
  constructor(pattern, flags) {
    const info = pyReParse(pattern, flags);
    this.pattern = pattern;
    this.flags = flags;
    this.groups = info.groups;
    this.groupindex = info.groupIndex;
    this.versionNotes = info.versionNotes;
    this._info = info;
    if (info.jsSource === null) {
      throw new PyReUntranslatable(/** @type {string} */ (info.untranslatable), pattern);
    }
    this._src = info.jsSource;
    this._flags = info.jsFlags;
  }

  /**
   * A fresh RegExp per call: `lastIndex` is mutable state, and `sub()` with a
   * function replacement can re-enter the same pattern.
   * @param {string} extra
   */
  _re(extra) {
    return new RegExp(this._src, this._flags + extra);
  }

  /** @param {number|string} key @returns {number} */
  _groupNumber(key) {
    if (typeof key === "number") {
      if (key < 0 || key > this.groups) throw new PyReError(`no such group: ${key}`);
      return key;
    }
    const gid = this.groupindex[key];
    if (gid === undefined) throw new PyReError(`no such group: '${key}'`);
    return gid;
  }

  /** py: Pattern.match — anchored at `pos`, not required to reach the end. */
  match(string, pos = 0, endpos = undefined) {
    const s = endpos === undefined ? string : string.slice(0, endpos);
    const re = this._re("yd");
    re.lastIndex = pos;
    const m = re.exec(s);
    return m ? new PyMatch(m, this, string) : null;
  }

  /**
   * py: Pattern.fullmatch. Sticky alone is not enough — the engine returns the
   * first alternative that matches at `pos`, not the one reaching the end — so
   * the end anchor goes into the source. `$` is a true end-of-input anchor here
   * because this module never emits the JS `m` flag (MULTILINE is desugared).
   */
  fullmatch(string, pos = 0, endpos = undefined) {
    const s = endpos === undefined ? string : string.slice(0, endpos);
    const re = new RegExp(`(?:${this._src})$`, this._flags + "yd");
    re.lastIndex = pos;
    const m = re.exec(s);
    return m ? new PyMatch(m, this, string) : null;
  }

  /** py: Pattern.search */
  search(string, pos = 0, endpos = undefined) {
    const s = endpos === undefined ? string : string.slice(0, endpos);
    const re = this._re("gd");
    re.lastIndex = pos;
    const m = re.exec(s);
    return m ? new PyMatch(m, this, string) : null;
  }

  /** py: Pattern.findall */
  findall(string) {
    const re = this._re("gd");
    re.lastIndex = 0;
    const out = [];
    let m;
    while ((m = re.exec(string)) !== null) {
      // py: Pattern.findall returns the whole match with 0 groups, the single
      // group with 1, and a tuple of groups otherwise; unmatched groups are "".
      if (this.groups === 0) out.push(m[0]);
      else if (this.groups === 1) out.push(m[1] === undefined ? "" : m[1]);
      else {
        const tup = [];
        for (let i = 1; i <= this.groups; i += 1) tup.push(m[i] === undefined ? "" : m[i]);
        out.push(tup);
      }
      if (m[0] === "") re.lastIndex += 1;
    }
    return out;
  }

  /** py: Pattern.finditer */
  *finditer(string) {
    const re = this._re("gd");
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(string)) !== null) {
      yield new PyMatch(m, this, string);
      if (m[0] === "") re.lastIndex += 1;
    }
  }

  /**
   * py: Pattern.sub
   * @param {string|((m: PyMatch) => string)} repl
   * @param {string} string
   * @param {number} [count] 0 means "all"
   */
  sub(repl, string, count = 0) {
    return this.subn(repl, string, count)[0];
  }

  /**
   * py: Pattern.subn
   * @param {string|((m: PyMatch) => string)} repl
   * @param {string} string
   * @param {number} [count]
   * @returns {[string, number]}
   */
  subn(repl, string, count = 0) {
    const tmpl =
      typeof repl === "string" ? pyReTemplate(repl, this.groups, this.groupindex) : null;
    const re = this._re("gd");
    re.lastIndex = 0;
    let out = "";
    let last = 0;
    let n = 0;
    let m;
    while ((m = re.exec(string)) !== null) {
      if (count !== 0 && n >= count) break;
      out += string.slice(last, m.index);
      out +=
        tmpl !== null
          ? tmpl.apply(m)
          : /** @type {(m: PyMatch) => string} */ (repl)(new PyMatch(m, this, string));
      last = m.index + m[0].length;
      n += 1;
      if (m[0] === "") re.lastIndex += 1;
    }
    out += string.slice(last);
    return [out, n];
  }

  /** py: Pattern.split */
  split(string, maxsplit = 0) {
    const re = this._re("gd");
    re.lastIndex = 0;
    const out = [];
    let last = 0;
    let n = 0;
    let m;
    while ((m = re.exec(string)) !== null) {
      if (maxsplit !== 0 && n >= maxsplit) break;
      if (m[0] === "" && m.index === last && m.index === 0) {
        re.lastIndex += 1;
        if (re.lastIndex > string.length) break;
        continue;
      }
      out.push(string.slice(last, m.index));
      for (let i = 1; i <= this.groups; i += 1) out.push(m[i] === undefined ? null : m[i]);
      last = m.index + m[0].length;
      n += 1;
      if (m[0] === "") re.lastIndex += 1;
    }
    out.push(string.slice(last));
    return out;
  }
}

