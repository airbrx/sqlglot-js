/* ------------------------------------------------------------------ errors */

/** Mirror of Python's `re.error`. */
export class PyReError extends Error {
  /**
   * @param {string} msg
   * @param {string} [pattern]
   * @param {number} [pos]
   */
  constructor(msg, pattern, pos) {
    super(pos === undefined ? msg : `${msg} at position ${pos}`);
    this.name = "PyReError";
    this.msg = msg;
    this.pattern = pattern;
    this.pos = pos;
  }
}

/**
 * Raised when a pattern is valid Python but has no faithful JS RegExp encoding.
 * Never raised by the oracle path (`pyReGroups` / `pyReParse`).
 */
export class PyReUntranslatable extends Error {
  /** @param {string} reason @param {string} [pattern] */
  constructor(reason, pattern) {
    super(`cannot translate Python regex to JavaScript: ${reason}`);
    this.name = "PyReUntranslatable";
    this.reason = reason;
    this.pattern = pattern;
  }
}

/* -------------------------------------------------- character-class sources
 *
 * Derived by a full 0..0x10FFFF sweep of CPython 3.9.25's `\w`, `\d`, `\s`
 * against candidate JS property escapes (spike/regex/corpus/py_unicode_classes.json,
 * regenerated by spike/py/gen_regex_cases.py --sweep).
 *
 *   \w  ==  [\p{L}\p{Nd}\p{Nl}\p{No}_]        0 CPython-only code points
 *   \d  ==  \p{Nd}                            0 CPython-only code points
 *   \s  ==  [\t\n\x0b\f\r\x20\x1c-\x1f\x85\p{Zs}  ]   exact, both directions
 *
 * `\w` and `\d` differ from CPython only on code points that CPython 3.9's Unicode
 * 13.0 database has as *unassigned* and Node 22's ICU 16.0 has as assigned
 * (9,917 and 110 code points respectively). That is a Unicode-database version skew,
 * not a semantic difference — see spike/regex/FINDINGS.md.
 */
const WORD_U = "\\p{L}\\p{Nd}\\p{Nl}\\p{No}_";
const DIGIT_U = "\\p{Nd}";
const SPACE_U = "\\t\\n\\x0b\\f\\r\\x20\\x1c-\\x1f\\x85\\p{Zs}\\u2028\\u2029";
const WORD_A = "A-Za-z0-9_";
const DIGIT_A = "0-9";
const SPACE_A = "\\t\\n\\x0b\\f\\r\\x20";

/* ---------------------------------------------------------------- charsets */

const DIGITS = "0123456789";
const OCTDIGITS = "01234567";
const HEXDIGITS = "0123456789abcdefABCDEF";
