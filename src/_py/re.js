// py: re._special_chars_map — CPython >= 3.7 escapes exactly this set.
const PY_ESCAPE_SET = "()[]{}?*+-|^$\\.&~# \t\n\r\v\f";
// The subset that is also a legal `IdentityEscape` under a JS `u`/`v` flag.
const JS_IDENTITY_SAFE = "()[]{}?*+|^$\\.";

/**
 * CPython `re.escape` semantics, emitting output that is valid inside a JS
 * `u`-flag (and `v`-flag) pattern.
 *
 * CPython escapes `- & ~ #` and the literal whitespace characters with a bare
 * backslash; `\-`, `\&`, `\~`, `\#` and `\<TAB>` are all SyntaxErrors under `/u`,
 * so those are emitted as numeric escapes instead. The resulting regex is
 * semantically identical and re-parses cleanly through {@link pyReParse}.
 *
 * py: sqlglot/optimizer/qualify_columns.py:1176,1182 — `re.escape(pattern[i])`
 * @param {string} s @returns {string}
 */
export function pyReEscape(s) {
  let out = "";
  for (const ch of s) {
    if (PY_ESCAPE_SET.includes(ch)) {
      out += JS_IDENTITY_SAFE.includes(ch)
        ? "\\" + ch
        : emitCp(/** @type {number} */ (ch.codePointAt(0)));
    } else {
      out += ch;
    }
  }
  return out;
}

/**
 * Byte-identical reproduction of CPython's `re.escape` output. Provided for
 * differential testing and for call sites that use the result as a *string*
 * rather than as regex source; it is NOT safe to drop into a JS `/u` pattern.
 * @param {string} s @returns {string}
 */
export function pyReEscapeExact(s) {
  let out = "";
  for (const ch of s) out += PY_ESCAPE_SET.includes(ch) ? "\\" + ch : ch;
  return out;
}

