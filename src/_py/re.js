// py: (Python stdlib `re` / `sre_parse` semantics shim — no single upstream file)
//
// sqlglot builds and uses Python regexes in places where build-time rewriting to JS
// regex literals is impossible, because the pattern is only known at runtime:
//
//   sqlglot/generator.py:1667   escape_pattern = re.compile(rf"{escape.name}(\d+)")
//   sqlglot/parsers/bigquery.py:127
//                               try:    group = re.compile(args[1].name).groups == 1
//                               except re.error: group = False
//
// Both take a *user-supplied SQL string* and hand it to `re`. So this module provides:
//
//   1. A Python-regex parser that computes `groups` / `groupindex` and Python validity
//      WITHOUT executing anything (the oracle `bigquery.py:127` needs).
//   2. A translator from Python regex source to a JS RegExp with matching semantics.
//   3. `pyReEscape` — CPython `re.escape` semantics, emitting `/u`-safe output.
//   4. `re.sub` replacement-template translation (`\1`, `\g<name>`  ->  `$1`, `$<name>`).
//
// The oracle and the translator MUST agree on group numbering, so they are the same
// single pass: `parsePattern()` always produces group data, and separately records
// whether a JS translation was possible. A pattern that JS cannot express still
// yields correct `groups` — that is exactly the `bigquery.py:127` path.
//
// Semantics are pinned to CPython 3.9 (the toolchain floor in PORT_PLAN.md §5.2).
// Version-sensitive behaviours are marked `VERSION-SENSITIVE` in comments below and
// reported through `parsePattern().versionNotes`.

