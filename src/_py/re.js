/**
 * @typedef {object} PyReTemplate
 * @property {Array<{lit:string}|{group:number}>} items  parsed template
 * @property {string|null} js   JS replacement string, or null when ambiguous
 * @property {string|null} ambiguous  reason the string form is unusable
 * @property {(m: RegExpExecArray) => string} apply  always-correct expansion
 */

/**
 * Parse a CPython `re.sub` replacement template and translate it to JS.
 *
 * CPython templates use `\1`..`\99` and `\g<name>` / `\g<0>`; JS uses `$1`,
 * `$<name>` and `$&`. Notable traps, all handled here:
 *
 *   - a literal `$` in the Python template must become `$$` in JS;
 *   - `\g<0>` is the whole match, which JS spells `$&` (`$0` is literal in JS);
 *   - `\\` is a literal backslash, and backslashes are NOT special in a JS
 *     replacement string, so `\\` becomes a single `\`;
 *   - inside a template `\b` is a backspace (U+0008), not a word boundary;
 *   - `\` + an ASCII letter that is not one of `abfnrtv` is a CPython error;
 *   - `\` + a non-letter (e.g. `\-`) keeps the backslash as a literal;
 *   - `$nn` is read greedily by JS, so `\1` followed by the literal digit `2`
 *     silently becomes group 12 when the pattern has >= 12 groups. That case is
 *     reported via `ambiguous` and `js === null`; use `apply` instead.
 *
 * py: sqlglot/generator.py:1660,1663 — `r"\\\1"` and `r"\\u\1"`
 * @param {string} template
 * @param {number} groups
 * @param {Record<string,number>} [groupIndex]
 * @returns {PyReTemplate}
 */
export function pyReTemplate(template, groups, groupIndex = {}) {
  /** @type {Array<{lit:string}|{group:number}>} */
  const items = [];
  /** @param {string} s */
  const lit = (s) => {
    const last = items[items.length - 1];
    if (last && "lit" in last) last.lit += s;
    else items.push({ lit: s });
  };

  let i = 0;
  while (i < template.length) {
    const ch = template[i];
    if (ch !== "\\") {
      lit(ch);
      i += 1;
      continue;
    }
    i += 1;
    if (i >= template.length) throw new PyReError("bad escape (end of pattern)", template, i - 1);
    const c = template[i];
    i += 1;

    if (c === "g") {
      if (template[i] !== "<") throw new PyReError("missing <", template, i);
      i += 1;
      let name = "";
      for (;;) {
        if (i >= template.length) throw new PyReError("missing >, unterminated name", template, i);
        const d = template[i];
        i += 1;
        if (d === ">") break;
        name += d;
      }
      if (name === "") throw new PyReError("missing group name", template, i);
      let gid;
      if (/^-?\d+$/.test(name)) {
        gid = Number(name);
        if (gid < 0) throw new PyReError(`bad character in group name '${name}'`, template, i);
      } else {
        if (!isPyIdentifier(name)) {
          throw new PyReError(`bad character in group name '${name}'`, template, i);
        }
        gid = groupIndex[name];
        if (gid === undefined) throw new PyReError(`unknown group name '${name}'`, template, i);
      }
      if (gid > groups) throw new PyReError(`invalid group reference ${gid}`, template, i);
      items.push({ group: gid });
      continue;
    }

    if (c === "0") {
      let oct = "";
      while (oct.length < 2 && i < template.length && OCTDIGITS.includes(template[i])) {
        oct += template[i];
        i += 1;
      }
      lit(String.fromCharCode(parseInt("0" + oct, 8) & 0xff));
      continue;
    }

    if (DIGITS.includes(c)) {
      let digits = c;
      if (i < template.length && DIGITS.includes(template[i])) {
        const two = digits + template[i];
        if (
          OCTDIGITS.includes(two[0]) &&
          OCTDIGITS.includes(two[1]) &&
          i + 1 < template.length &&
          OCTDIGITS.includes(template[i + 1])
        ) {
          const three = two + template[i + 1];
          i += 2;
          const v = parseInt(three, 8);
          if (v > 0o377) {
            throw new PyReError(
              `octal escape value \\${three} outside of range 0-0o377`,
              template,
              i,
            );
          }
          lit(String.fromCharCode(v));
          continue;
        }
        digits = two;
        i += 1;
      }
      const gid = Number(digits);
      if (gid > groups) throw new PyReError(`invalid group reference ${gid}`, template, i - 1);
      items.push({ group: gid });
      continue;
    }

    if (c in ESCAPE_CHARS) {
      lit(String.fromCharCode(ESCAPE_CHARS[/** @type {keyof typeof ESCAPE_CHARS} */ (c)]));
      continue;
    }
    if (ASCIILETTERS.includes(c)) throw new PyReError(`bad escape \\${c}`, template, i - 2);
    // `\` + non-letter keeps both characters, e.g. `\-` -> `\-`
    lit("\\" + c);
  }

  // ---- JS replacement-string form, with the `$nn` greediness check ----
  let js = "";
  let ambiguous = null;
  for (let k = 0; k < items.length; k += 1) {
    const it = items[k];
    if ("lit" in it) {
      js += it.lit.replace(/\$/g, "$$$$");
      continue;
    }
    if (it.group === 0) {
      js += "$&";
      continue;
    }
    const nextItem = items[k + 1];
    const nextChar =
      nextItem && "lit" in nextItem && nextItem.lit.length > 0 ? nextItem.lit[0] : "";
    // NB: `"...".includes("")` is always true, so the empty case must be excluded.
    if (nextChar !== "" && DIGITS.includes(nextChar)) {
      const twoDigit = Number(String(it.group) + nextChar);
      // JS tries the 2-digit reading first and only falls back when it exceeds
      // the group count.
      if (it.group < 10 && twoDigit <= groups) {
        ambiguous = `\\${it.group} followed by literal '${nextChar}' is indistinguishable from $${twoDigit}`;
      }
    }
    js += "$" + it.group;
  }
  if (ambiguous !== null) js = null;

  return {
    items,
    js,
    ambiguous,
    /** @param {RegExpExecArray} m */
    apply(m) {
      let out = "";
      for (const it of items) {
        if ("lit" in it) out += it.lit;
        else out += m[it.group] === undefined ? "" : m[it.group];
      }
      return out;
    },
  };
}

