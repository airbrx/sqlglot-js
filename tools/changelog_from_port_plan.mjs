// Generates CHANGELOG.md from PORT_PLAN.md's own "**R<n> — ...**" round entries.
//
// Each round in PORT_PLAN.md opens its own paragraph with a single bolded sentence (or
// short run of sentences) summarizing what landed, e.g.:
//   **R116 — AIR-2311 (epic AIR-2271, "..."): the both-ported `SQL_MISMATCH` population
//   goes 39 rows / 19 clusters → **1 row / 1 cluster**, ... → **1 / 0** — ... **
// A short INTERNAL `**...**` span (a number, a word) never ends right before a period —
// only the paragraph's own closing does — so a lazy match up to the first ".**" finds the
// real end of the bolded summary even when the summary itself contains nested bold spans.
//
// Usage: node tools/changelog_from_port_plan.mjs > CHANGELOG.md

import { readFileSync } from "node:fs";

const PORT_PLAN_PATH = "PORT_PLAN.md";
const V0_ROUND = 116; // PORT_PLAN.md R116 — tag v0.0.1 points at this round's commit (6949184).

// Tier 1 (the shape every port-landing round R38+ uses): the whole highlight is ONE bold
// span, possibly itself containing short nested bold phrases (a number, a word) that never
// happen to end right before a period — so a lazy match up to the first ".**" finds the
// real close.
const STRICT_RE = /^\*\*R(\d+)\s*—\s*(.*?\.)\*\*/;

// Tier 2 fallback (the shape some early risk-register entries, R1–R37-ish, use instead:
// one or two SHORT bold phrases inside an otherwise-plain paragraph, with no single bold
// span wrapping the whole thing). Capture from the dash to the LAST "**" anywhere in the
// line — effectively "the paragraph, minus its own unbolded tail clause" — or, if the line
// has no further "**" at all, up to the first sentence break, else the whole line.
const HEAD_RE = /^\*\*R(\d+)\s*—\s*(.*)$/;

function fallbackSummary(rest) {
  const lastBold = rest.lastIndexOf("**");
  if (lastBold !== -1) return rest.slice(0, lastBold);
  const sentenceEnd = rest.indexOf(". ");
  return sentenceEnd !== -1 ? rest.slice(0, sentenceEnd + 1) : rest;
}

function clean(summary) {
  return summary.replace(/\*\*/g, "").trim();
}

function extractEntries(text) {
  const entries = [];
  for (const line of text.split("\n")) {
    const strict = STRICT_RE.exec(line);
    if (strict) {
      entries.push({ round: Number(strict[1]), summary: clean(strict[2].trim()) });
      continue;
    }
    const head = HEAD_RE.exec(line);
    if (!head) continue;
    entries.push({ round: Number(head[1]), summary: clean(fallbackSummary(head[2]).trim()) });
  }
  entries.sort((a, b) => a.round - b.round);
  for (const entry of entries) {
    const issueMatch = /AIR-\d+/.exec(entry.summary);
    entry.issue = issueMatch ? issueMatch[0] : null;
  }
  return entries;
}

function render(entries) {
  const lines = [
    "# Changelog",
    "",
    "Generated by `tools/changelog_from_port_plan.mjs` from PORT_PLAN.md's own round-by-round",
    "entries (`**R<n> — ...**`) — one line per round, newest first. Each entry is this repo's",
    "own highlight sentence for that round, not independently re-written; see PORT_PLAN.md",
    "itself for the full per-round detail (every file touched, every bug found) and",
    "docs/stability.md for what \"parity\" and the version markers below mean.",
    "",
  ];

  for (const entry of [...entries].reverse()) {
    const tag = entry.round === V0_ROUND ? " — **`v0.0.1`**" : "";
    // The summary text usually already opens with its own issue reference
    // ("AIR-2313 (epic ...): ..." or "AIR-2308/AIR-2309/AIR-2310, epics ..."); strip that
    // redundant leading mention before re-prefixing with the plain issue id so the line
    // reads "R<n> (AIR-nnnn): <summary>" once, not twice.
    let summary = entry.summary;
    if (entry.issue) {
      summary = summary.replace(/^AIR-\d+(?:\/AIR-\d+)*\s*/, "").replace(/^\(([^)]*)\):\s*/, "$1: ");
    }
    const issue = entry.issue ? ` (${entry.issue})` : "";
    lines.push(`- **R${entry.round}**${issue}${tag} — ${summary}`);
  }

  lines.push("");
  return lines.join("\n");
}

const text = readFileSync(PORT_PLAN_PATH, "utf8");
const entries = extractEntries(text);
process.stdout.write(render(entries));
